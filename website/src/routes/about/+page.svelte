    <h1>About Harvey</h1>
    <p>
        Harvey is a desktop application for qualitative researchers and anyone working with multimedia content. It streamlines the research workflow by integrating a powerful suite of tools into a single, cohesive environment:
    </p>
    <ul>
        <li><strong>Transcribe</strong> audio and video with local AI models.</li>
        <li><strong>Translate</strong> transcripts into English.</li>
        <li><strong>Edit</strong> and <strong>annotate</strong> transcripts, documents, PDFs, and images.</li>
        <li><strong>Manage</strong> all your project files in one place.</li>
    </ul>
    <p>
        Harvey is named in honor of Sociologist <a href="https://en.wikipedia.org/wiki/Harvey_Sacks" target="_blank" rel="noreferrer">Harvey Sacks</a> (1935-1975), whose foundational work revolutionized social research methods.
    </p>

    <h2>Privacy First</h2>
    <p>
        Privacy is the core of Harvey's design. All core AI functionalities, like transcription and diarization (speaker identification), run <strong>100% locally</strong> on your computer. You download the AI models once and can use them forever offline. Your data never leaves your device.
    </p>
    <blockquote>
        It's an application built <em>by researchers, for researchers</em>.
    </blockquote>

    <h2>Developed with AI</h2>
    <p>
        From its inception, Project Harvey has been significantly developed using AI tools, including Gemini, Google AI Studio, and Google Jules. We believe this AI-assisted approach can make development more accessible and efficient, and we encourage contributors to explore and adopt similar methods.
    </p>

    <h2>Open Source</h2>
    <p>
        Harvey is free and open-source software. The code is available on <a href="https://github.com/Ethnomethodology/harvey" target="_blank" rel="noreferrer">GitHub</a>, and we welcome contributions from the community.
    </p>
